package ru.slie.luna.maven.mojo;

import org.apache.maven.model.Resource;
import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.project.MavenProject;
import ru.slie.luna.maven.I18nResolver;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Removes resources that are gone from the sources from the output directory.
 * <p>
 * maven-resources-plugin only copies files, so a resource deleted or renamed in {@code src/main/resources} stays in
 * {@code target/classes} and gets into the plugin jar until {@code mvn clean}. Bundlers make this the usual case:
 * every frontend build emits chunks with new hashes, and the old ones pile up.
 * <p>
 * Runs before the resources are copied. The files copied by the previous build are listed in a manifest; those that
 * are no longer in the resource directories are deleted. Nothing else in the output directory is touched: classes
 * and files generated by the compiler or other plugins stay. The first build with this goal only writes the manifest,
 * so the files left by older builds go away with one {@code mvn clean}.
 */
@Mojo(name = "sync-resources", defaultPhase = LifecyclePhase.PROCESS_RESOURCES, threadSafe = true)
public class SyncResourcesMojo extends AbstractMojo {
    static final String MANIFEST = "luna-plugin/resources.lst";

    @Parameter(defaultValue = "${project}", readonly = true, required = true)
    private MavenProject project;

    @Parameter(property = "luna.syncResources.skip", defaultValue = "false")
    private boolean skip;

    private final I18nResolver i18n = new I18nResolver();

    @Override
    public void execute() throws MojoExecutionException {
        if (skip) {
            return;
        }
        Path outputDir = Paths.get(project.getBuild().getOutputDirectory()).toAbsolutePath().normalize();
        Path manifest = Paths.get(project.getBuild().getDirectory()).resolve(MANIFEST);
        try {
            Set<String> current = resourceFiles(project.getResources(), outputDir);
            List<String> removed = removeStale(outputDir, readManifest(manifest), current);
            if (!removed.isEmpty()) {
                getLog().info(i18n.t("luna.resources.removed_stale", removed.size()));
                removed.forEach(path -> getLog().debug(" - " + path));
            }
            Files.createDirectories(manifest.getParent());
            Files.write(manifest, current, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new MojoExecutionException(i18n.t("luna.resources.sync_error"), e);
        }
    }

    /** Paths, relative to the output directory, of all files the resources plugin is going to copy. */
    static Set<String> resourceFiles(List<Resource> resources, Path outputDir) throws IOException {
        Set<String> out = new TreeSet<>();
        for (Resource resource : resources) {
            Path dir = Paths.get(resource.getDirectory());
            if (!Files.isDirectory(dir)) {
                continue;
            }
            Path target = outputDir;
            if (resource.getTargetPath() != null && !resource.getTargetPath().isBlank()) {
                target = outputDir.resolve(resource.getTargetPath()).normalize();
            }
            if (!target.startsWith(outputDir)) {
                continue; // copied outside of the jar contents
            }
            Path base = target;
            try (Stream<Path> files = Files.walk(dir)) {
                for (Path file : (Iterable<Path>) files.filter(Files::isRegularFile)::iterator) {
                    out.add(toKey(outputDir.relativize(base.resolve(dir.relativize(file).toString()))));
                }
            }
        }
        return out;
    }

    /** Deletes files of the previous build that are not resources any more, and directories left empty. */
    static List<String> removeStale(Path outputDir, Set<String> previous, Set<String> current) throws IOException {
        List<String> removed = new ArrayList<>();
        for (String path : previous) {
            if (current.contains(path)) {
                continue;
            }
            Path file = outputDir.resolve(path).normalize();
            if (!file.startsWith(outputDir) || !Files.isRegularFile(file)) {
                continue;
            }
            Files.delete(file);
            removed.add(path);
            for (Path dir = file.getParent(); dir != null && !dir.equals(outputDir) && isEmptyDir(dir); dir = dir.getParent()) {
                Files.delete(dir);
            }
        }
        return removed;
    }

    private static Set<String> readManifest(Path manifest) throws IOException {
        Set<String> out = new TreeSet<>();
        if (Files.isRegularFile(manifest)) {
            for (String line : Files.readAllLines(manifest, StandardCharsets.UTF_8)) {
                if (!line.isBlank()) {
                    out.add(line.trim());
                }
            }
        }
        return out;
    }

    private static boolean isEmptyDir(Path dir) throws IOException {
        if (!Files.isDirectory(dir)) {
            return false;
        }
        try (Stream<Path> entries = Files.list(dir)) {
            return entries.findAny().isEmpty();
        }
    }

    private static String toKey(Path relative) {
        return relative.toString().replace('\\', '/');
    }
}
